function fail(message) {
  throw new Error(message);
}

/** Slices the top-level `const <name> = <literal>` out of a page and evaluates the literal. */
async function readLiteral(page, name) {
  const file = path.join(SOURCE, page);
  const source = ts.createSourceFile(file, await readFile(file, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const assets = new Map(); // import identifier → asset file name, e.g. evalGuardImage → "eval-guard-report.png"
  let literal;
  for (const statement of source.statements) {
    if (ts.isImportDeclaration(statement) && ts.isStringLiteral(statement.moduleSpecifier)) {
      const from = statement.moduleSpecifier.text;
      const local = statement.importClause?.name?.text;
      if (local && from.startsWith("@/assets/")) assets.set(local, from.slice("@/assets/".length));
    } else if (ts.isVariableStatement(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name) && declaration.name.text === name) literal = declaration.initializer;
      }
    }
  }
  if (!literal) fail(`${page}: no top-level \`const ${name} = …\``);
  const { outputText, diagnostics = [] } = ts.transpileModule(`(${literal.getText(source)});`, {
    compilerOptions: { target: ts.ScriptTarget.ES2022 },
    reportDiagnostics: true,
  });
  if (diagnostics.length) {
    fail(`${page}: \`${name}\` does not transpile: ${ts.flattenDiagnosticMessageText(diagnostics[0].messageText, " ")}`);
  }
  try {
    return new Function(...assets.keys(), `"use strict"; return ${outputText}`)(...assets.values());
  } catch (error) {
    fail(`${page}: evaluating \`${name}\` failed: ${error.message}`);
  }
}

/** Reads a typed field, failing loudly when it is missing (unless optional) or has the wrong shape. */
function field(entry, key, type, where, { optional = false } = {}) {
  const value = entry[key];
  if (value === undefined && optional) return undefined;
  const ok =
    type === "string[]" ? Array.isArray(value) && value.every((item) => typeof item === "string")
    : type === "array" ? Array.isArray(value)
    : typeof value === type;
  if (!ok) fail(`${where}: \`${key}\` should be ${optional ? "absent or " : ""}${type}, got ${q(value)}`);
  return value;
}

function sameIds(what, actual, expected) {
  const dupes = actual.ids.filter((id, i) => actual.ids.indexOf(id) !== i);
  if (dupes.length) fail(`${what}: duplicate ids in ${actual.name}: ${dupes.join(", ")}`);
  const extra = actual.ids.filter((id) => !expected.ids.includes(id));
  const missing = expected.ids.filter((id) => !actual.ids.includes(id));
  if (extra.length || missing.length) {
    fail(
      `${what}: ${actual.name} and ${expected.name} disagree. ` +
        `Only in ${actual.name}: ${extra.join(", ") || "none"}. Only in ${expected.name}: ${missing.join(", ") || "none"}.`,
    );
  }
}

function byN(entries, what) {
  for (const { id, n } of entries) if (!/^\d+$/.test(n)) fail(`${what} ${id}: n should be digits, got ${q(n)}`);
  const ns = entries.map((entry) => entry.n);
  const dupes = ns.filter((n, i) => ns.indexOf(n) !== i);
  if (dupes.length) fail(`${what}: duplicate n values: ${dupes.join(", ")}`);
  return [...entries].sort((a, b) => Number(a.n) - Number(b.n));
}

const paragraphs = (text) => text.split(/\n\s*\n/).map((paragraph) => paragraph.trim()).filter(Boolean);
const assetFile = (ref) =>
  ref.startsWith("clone:")
    ? path.join(ROOT, ref.slice("clone:".length))
    : ref.startsWith("/")
      ? path.join(SOURCE, "public", ref)
      : path.join(SOURCE, "src/assets", ref);

// ── images ───────────────────────────────────────────────────────────────────────────────────────────
const images = []; // { ref, src, copy } in output order
const planned = new Map(); // public path → the cover objects that point at it (so a later pass can set `fit`)
const LOGO_MAX_WIDTH = 900; // raster covers narrower than this are logos
const writers = new Map(); // public path → source ref, so two sources never fight over one file

/**
 * Plans one output image and returns its { src, tone }. Every image is shown as it was in the portfolio:
 * SVGs and cover images are copied byte for byte (the page crops covers with object-fit, like the old site);
 * "native" rasters (diagrams) are re-encoded to WebP at their own size, colours untouched.
 */
function planImage(ref, dir, name, mode) {
  const ext = path.extname(ref).toLowerCase();
  const copy = ext === ".svg" || mode === "cover";
  const src = `/images/${dir}/${name}${copy ? ext : ".webp"}`;
  const writer = writers.get(src);
  if (writer && writer !== ref) fail(`${src} would be written from both ${writer} and ${ref}`);
  if (!writer) {
    writers.set(src, ref);
    images.push({ ref, src, copy });
  }
  const cover = { src, tone: "original" };
  planned.set(src, [...(planned.get(src) ?? []), cover]);
  return cover;
}

async function renderImage({ ref, src, copy }) {
  const from = assetFile(ref);
  const to = path.join(ROOT, "public", src);
  await mkdir(path.dirname(to), { recursive: true });
  if (copy) return copyFile(from, to);
  return sharp(from).autoOrient().webp(WEBP).toFile(to);
}

// ── projects ─────────────────────────────────────────────────────────────────────────────────────────
async function buildProjects() {
  const list = await readLiteral("src/pages/Projects.tsx", "projects");
  const details = await readLiteral("src/pages/ProjectDetailPage.tsx", "projectsData");
  const listIds = { name: "Projects.tsx", ids: list.map((item) => item.id) };
  sameIds("projects", listIds, { name: "ProjectDetailPage.tsx", ids: Object.keys(details) });
  sameIds("projects", listIds, { name: "the category mapping", ids: Object.keys(PROJECT_CATEGORIES) });

  return byN(list, "project").map((item) => {
    const { id } = item;
    const detail = details[id];
    const where = `project ${id}`;
    const codeSnippet = field(detail, "codeSnippet", "string", where, { optional: true });
    const diagrams = [...(field(detail, "diagrams", "array", where, { optional: true }) ?? []), ...(EXTRA_DIAGRAMS[id] ?? [])];
    return {
      id,
      n: field(item, "n", "string", where),
      title: field(detail, "title", "string", where),
      category: PROJECT_CATEGORIES[id],
      excerpt: field(item, "description", "string", where),
      description: field(detail, "description", "string", where),
      paragraphs: paragraphs(field(detail, "fullDescription", "string", where)),
      technologies: field(detail, "technologies", "string[]", where),
      github: field(detail, "github", "string", where),
      live: field(detail, "live", "string", where, { optional: true }) ?? field(item, "live", "string", where, { optional: true }),
      reportUrl: field(detail, "reportUrl", "string", where, { optional: true }),
      cover: planImage(COVER_OVERRIDES[id] ?? field(item, "image", "string", where), "projects", id, "cover"),
      features: field(detail, "features", "string[]", where, { optional: true }) ?? [],
      code:
        codeSnippet === undefined
          ? undefined
          : {
              // Same fallback the old site used when a project sets no language.
              language:
                field(detail, "language", "string", where, { optional: true }) ??
                (field(detail, "technologies", "string[]", where).some((t) => /react|typescript/i.test(t)) ? "typescript" : "python"),
              source: codeSnippet,
            },
      diagrams: diagrams.map((diagram, i) => {
        const at = `${where} diagram ${i + 1}`;
        const ref = field(diagram, "src", "string", at);
        return {
          ...planImage(ref, "projects", path.basename(ref, path.extname(ref)), "native"),
          title: field(diagram, "title", "string", at),
          caption: field(diagram, "caption", "string", at),
        };
      }),
    };
  });
}

// ── engagements ──────────────────────────────────────────────────────────────────────────────────────
async function buildEngagements() {
  const list = await readLiteral("src/pages/Engagement.tsx", "engagements");
  const details = await readLiteral("src/pages/EngagementDetail.tsx", "engagementsData");
  const listIds = { name: "Engagement.tsx", ids: list.map((item) => item.id) };
  sameIds("engagements", listIds, { name: "EngagementDetail.tsx", ids: Object.keys(details) });
  sameIds("engagements", listIds, { name: "the category mapping", ids: Object.keys(ENGAGEMENT_CATEGORIES) });

  return byN(list, "engagement").map((item) => {
    const { id } = item;
    const detail = details[id];
    const where = `engagement ${id}`;
    // Header fields come from the list (what the cards show), falling back to the detail page.
    const fromList = (key, fallback = key) =>
      field(item, key, "string", where, { optional: true }) ?? field(detail, fallback, "string", where);
    return {
      id,
      n: field(item, "n", "string", where),
      title: fromList("title"),
      role: fromList("role"),
      period: fromList("period"),
      commitment: fromList("commitment", "timeCommitment"),
      summary: field(item, "summary", "string", where),
      category: ENGAGEMENT_CATEGORIES[id],
      work: paragraphs(field(detail, "work", "string", where)),
      learned: paragraphs(field(detail, "learned", "string", where)),
      relevance: paragraphs(field(detail, "relevance", "string", where)),
      cover: planImage(ENGAGEMENT_COVER_OVERRIDES[id] ?? field(item, "image", "string", where), "engagement", id, "cover"),
    };
  });
}

// ── main ─────────────────────────────────────────────────────────────────────────────────────────────
async function main() {
  const projects = await buildProjects();
  const engagements = await buildEngagements();

  for (const id of FEATURED_PROJECT_IDS) if (!projects.some((p) => p.id === id)) fail(`featured project ${id} does not exist`);
  for (const { id } of CURRENT_ENGAGEMENTS) if (!engagements.some((e) => e.id === id)) fail(`current engagement ${id} does not exist`);

  const missing = [];
  for (const { ref } of images) {
    await access(assetFile(ref)).catch(() => missing.push(path.relative(SOURCE, assetFile(ref))));
  }
  if (missing.length) fail(`missing image files in ${SOURCE}: ${missing.join(", ")}`);
  for (const image of images) await renderImage(image);
  // Small raster covers are logos: show them whole on white rather than cropping their text away.
  for (const image of images) {
    if (!image.copy || image.src.endsWith(".svg")) continue;
    const { width = 0 } = await sharp(assetFile(image.ref)).metadata();
    if (width < LOGO_MAX_WIDTH) for (const cover of planned.get(image.src) ?? []) cover.fit = "contain";
  }

  const contentDir = path.join(ROOT, "src/content");
  await mkdir(contentDir, { recursive: true });
  await writeFile(
    path.join(contentDir, "projects.ts"),
    `${PROJECTS_HEADER}export const projects: Project[] = ${JSON.stringify(projects, null, 2)};\n` +
      "export const getProject = (id: string) => projects.find((p) => p.id === id);\n",
  );
  await writeFile(
    path.join(contentDir, "engagement.ts"),
    `${ENGAGEMENT_HEADER}export const engagements: Engagement[] = ${JSON.stringify(engagements, null, 2)};\n` +
      "export const getEngagement = (id: string) => engagements.find((e) => e.id === id);\n",
  );

  console.log(`Extracted from ${SOURCE}`);
  console.log(`  ${projects.length} projects    → src/content/projects.ts`);
  console.log(`  ${engagements.length} engagements → src/content/engagement.ts`);
  console.log(`  ${images.length} images:`);
  for (const { ref, src, copy } of images) {
    console.log(`    ${src.padEnd(46)} ${copy ? "copied " : "re-encoded"}  ← ${path.relative(SOURCE, assetFile(ref))}`);
  }
}

main().catch((error) => {
  console.error(`extract-portfolio: ${error.message}`);
  process.exitCode = 1;
});
