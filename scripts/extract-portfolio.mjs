// Extracts Sheng's projects and engagements from his portfolio repo into typed content modules plus
// processed images.
//
//   source (read-only): github.com/shengdynasty/cool-website, a local checkout
//     src/pages/Projects.tsx            `projects`         list: id, n, description (excerpt), image
//     src/pages/ProjectDetailPage.tsx   `projectsData`     detail: title, description, fullDescription, …
//     src/pages/Engagement.tsx          `engagements`      list: id, n, title, role, period, commitment, summary, image
//     src/pages/EngagementDetail.tsx    `engagementsData`  detail: timeCommitment, work, learned, relevance
//   output
//     src/content/projects.ts, src/content/engagement.ts
//     public/images/projects/*, public/images/engagement/*
//
// Each data literal is sliced out of its page with the TypeScript parser (which leaves the declaration's
// type annotation behind), transpiled to plain JavaScript, and evaluated with every
// `import x from "@/assets/…"` identifier bound to its asset file name. Strings come out exactly as the
// site renders them, escaped backticks and all. Nothing is hand-copied.
//
// Usage: node scripts/extract-portfolio.mjs [path/to/cool-website]
//        (default: $PORTFOLIO_SRC, else /Users/shengyan/cool-website)
